# operasi tambah +
x = 26
y = 12
hasil_tambah = x + y
print(x, "+", y, "=", hasil_tambah)

# operasi kurang -
x = 26
y = 12
hasil_kurang = x - y
print(x, "-", y, "=", hasil_kurang)

# operasi kali *
x = 26
y = 12  
hasil_kali = x * y
print(x, "*", y, "=", hasil_kali)

# operasi bagi /
x = 26
y = 12  
hasil_bagi = x / y
print(x, "/", y, "=", hasil_bagi)

# operasi modulus %
# menghasilkan sisa hasil bagi dari pembagian x dengan y
# misal 26 dibagi 12 hasilnya 2 sisa 2, jadi modulus 2
x = 26
y = 12
hasil_modulus = x % y
print(x, "%", y, "=", hasil_modulus)

# operasi pangkat **
# bilangan x dikalikan dengan dirinya sendiri sebanyak y
x = 26
y = 12  
hasil_pangkat = x ** y
print(x, "**", y, "=", hasil_pangkat)   

# operasi floor division //
# membulatkan hasil pembagian ke bawah
x = 26      
y = 12
hasil_floor_division = x // y
print(x, "//", y, "=", hasil_floor_division)