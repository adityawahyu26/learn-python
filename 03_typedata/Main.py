# tipe data string
string = "hello string"
print(string)
print("Type of data:", type(string))

# tipe data integer
integer = 10
print(integer)  
print("Type of data:", type(integer))

# tipe data float
float_num = 10.5
print(float_num)
print("Type of data:", type(float_num))

# tipe data boolean
boolean = True
print(boolean)
print("Type of data:", type(boolean))

# tipe data list
list_data = [1, 2, 3, 4, 5]
print(list_data)
print("Type of data:", type(list_data))

# import library ctypes dengan tipe data c_double
from ctypes import c_double
rhine = c_double(1.0)
print(rhine)
print("Type of data:", type(rhine))