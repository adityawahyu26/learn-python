# data tuples dan data sets

# data list biasa, bisa diubah valuenya
data_list = [23,34,52,12,67]
print("data list biasa :")
print(data_list)

# data tuples, tidak bisa diubah valuenya
data_tuples = (123,454,345,123,231)
print("data tuples :")
print(data_tuples)

# data sets / himpunan, secara otomatis mengurutkan valuenya
data_sets = {9,3,1,5,3,7,2,7,5,7,8,2}
print("data sets / himpunan :")
print(data_sets)


