# operator komparasi atau perbandingan

x = 26
y = 12

# lebih besar dari >
hasil = x > y
print(x, ">", y, "=", hasil)

# lebih kecil dari <
hasil = x < y
print(x, "<", y, "=", hasil)

# lebih besar dari sama dengan >=
hasil = x >= y
print(x, ">=", y, "=", hasil)

# lebih kecil dari sama dengan <=
hasil = x <= y
print(x, "<=", y, "=", hasil)

# sama dengan ==
hasil = x == y
print(x, "==", y, "=", hasil)

# tidak sama dengan !=
hasil = x != y  
print(x, "!=", y, "=", hasil)

